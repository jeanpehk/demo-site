const addDefaultFlexContainerStyles = (container, direction) => {
    container.style.display = "flex";
    container.style.flexDirection = direction;
    container.style.flexWrap = "nowrap";
    container.style.justifyContent = "center";
    container.style.alignItems = "center";
    container.style.alignContent = "center";
}

const Nav = (links) => {
    const nav = document.createElement("nav");

    const navStyle = document.createElement("style");
    nav.appendChild(navStyle);

    {
        const ul = document.createElement("ul");
        ul.id = "nav-ul-container";

        addDefaultFlexContainerStyles(ul, "row");

        ul.style.margin = "0px";
        ul.style.padding = "0px";
        ul.style.listStylePosition = "inside";
        ul.style.listStyleType = "none";

        const liClassName = ul.id + "-item";
        const aClassName = "nav-li-a";

        navStyle.textContent += `
           .${aClassName} {
               margin: 0px;
               padding: 4px;
               text-decoration: none;
               transition: 0.1s;
               color: gray;
           }
        `;

         navStyle.textContent += `
           .${aClassName}:hover {
               color: black;
           }
        `;

        const addLi = (aHref, aText) => {
            const li = document.createElement("li");
            li.className = liClassName;
            li.style.padding = "6px";

            const a = document.createElement("a");
            a.className = aClassName;
            a.href = aHref;
            a.text = aText;

            li.appendChild(a);

            ul.appendChild(li);
        };

        for (const link of links) {
            addLi(link.href, link.text);
        }

        nav.appendChild(ul);
    }

    return nav;
};

