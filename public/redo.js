const DEFAULT_HEADER_COLOR = "black";
const DEFAULT_TEXT_COLOR = "#16181F";
const DEFAULT_PADDING = "6px";
const DEFAULT_MARGIN = "6px";
const HEADER_HEIGHT = "4rem";

// @Todo: style.textContent CSS adds work awkwardly (priorities) together with setting directly with e.g. style.margin = ..
